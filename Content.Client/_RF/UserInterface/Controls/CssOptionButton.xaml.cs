using System.Numerics;
using Content.Client._RF.CSS;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RF.UserInterface.Controls;

/// <summary>
/// A button that opens a list of items to choose from, the <see cref="CssControl"/> version of
/// <see cref="Robust.Client.UserInterface.Controls.OptionButton"/>.
/// </summary>
/// <remarks>
/// <para>
/// The layout is in <c>CssOptionButton.xaml</c> (the label and the triangle) and
/// <c>CssOptionButtonPopup.xaml</c> (the list). The button is a toggle: it is <see cref="CssButton.Pressed"/>
/// (<c>:checked</c>) while the list is open, and pressing it again closes the list.
/// </para>
/// <para>
/// Items are identified by the <see cref="CssOptionItem"/> that <see cref="AddItem"/> returns, there are no
/// ids or indices. What the item stands for goes into <see cref="CssOptionItem.Value"/>:
/// <code>
/// var button = new CssOptionButton();
/// button.AddItem("Male", Sex.Male);
/// button.OnItemSelected += args => Use((Sex) args.Value!);
/// button.SelectValue(Sex.Female);
/// </code>
/// </para>
/// <para>
/// The label is <c>.option-button</c>, the triangle is <c>.option-triangle</c> (plus <c>.checked</c> while the
/// list is open), the list is
/// <c>.option-button-panel</c> and its items are <c>.option-item</c> (a <c>css-button</c>, the selected one
/// is <c>:checked</c>).
/// </para>
/// </remarks>
[GenerateTypedNameReferences]
[Virtual, UsedImplicitly]
public partial class CssOptionButton : CssButton
{

    private readonly CssOptionButtonPopup _popup = new();
    private readonly List<CssOptionItem> _items = new();

    /// <summary>
    /// The items, in the order they are shown.
    /// </summary>
    [PublicAPI, ViewVariables]
    public IReadOnlyList<CssOptionItem> Items => _items;

    /// <summary>
    /// The chosen item, <c>null</c> when there are no items.
    /// </summary>
    [PublicAPI, ViewVariables]
    public CssOptionItem? Selected { get; private set; }

    /// <summary>
    /// <see cref="CssOptionItem.Value"/> of the <see cref="Selected"/> item.
    /// </summary>
    [PublicAPI, ViewVariables]
    public object? SelectedValue => Selected?.Value;

    /// <summary>
    /// Is the list of items open.
    /// </summary>
    [PublicAPI, ViewVariables]
    public bool IsOpen => _popup.Visible;

    /// <summary>
    /// The text shown before the text of the selected item.
    /// </summary>
    [PublicAPI]
    public string Prefix
    {
        get;
        set
        {
            field = value;
            UpdateLabel();
        }
    } = string.Empty;

    /// <summary>
    /// If true, hides the triangle to the right of the label.
    /// </summary>
    [PublicAPI]
    public bool HideTriangle
    {
        get;
        set
        {
            field = value;
            Triangle.Visible = !value;
        }
    }

    /// <summary>
    /// If true, the list has a field that hides the items which don't contain its text.
    /// </summary>
    [PublicAPI]
    public bool Filterable
    {
        get;
        set
        {
            field = value;
            _popup.FilterBox.Visible = value;
            UpdateFilters();
        }
    }

    /// <summary>
    /// CSS style classes of the buttons of all items, the existing and the added afterwards
    /// (<see cref="CssClass.OptionItem"/> is always there). Assign a new collection to change them, in XAML:
    /// <c>ItemCssStyleClasses="open-both gold"</c>. The classes of one item are <see cref="CssOptionItem.CssStyleClasses"/>.
    /// </summary>
    /// <remarks>
    /// The list lives in the modal root, not inside the button, so a selector like <c>css-option-button .option-item</c>
    /// does not reach it: select the items by their own classes.
    /// </remarks>
    [PublicAPI]
    public CssStyleClassCollection ItemCssStyleClasses
    {
        get;
        set
        {
            var old = field;
            field = value;

            foreach (var item in _items)
            {
                foreach (var styleClass in old)
                {
                    item.Button.RemoveCssStyleClass(styleClass);
                }

                foreach (var styleClass in value)
                {
                    item.Button.AddCssStyleClass(styleClass);
                }
            }
        }
    } = new();

    /// <summary>
    /// CSS style identifier (<c>#id</c>) of the buttons of all items.
    /// </summary>
    [PublicAPI]
    public string? ItemCssStyleIdentifier
    {
        get;
        set
        {
            field = value;

            foreach (var item in _items)
            {
                item.Button.CssStyleIdentifier = value;
            }
        }
    }

    /// <summary>
    /// CSS style classes of the list that holds the items, <see cref="CssClass.OptionButtonPanel"/> is there by
    /// default. Setting adds the classes to the existing ones.
    /// </summary>
    [PublicAPI]
    public CssStyleClassCollection PopupCssStyleClasses
    {
        get => _popup.Scroll.CssStyleClasses;
        set
        {
            foreach (var styleClass in value)
            {
                _popup.Scroll.AddCssStyleClass(styleClass);
            }
        }
    }

    /// <summary>
    /// CSS style identifier (<c>#id</c>) of the list that holds the items.
    /// </summary>
    [PublicAPI]
    public string? PopupCssStyleIdentifier
    {
        get => _popup.Scroll.CssStyleIdentifier;
        set => _popup.Scroll.CssStyleIdentifier = value;
    }

    /// <summary>
    /// The field that filters the items, see <see cref="Filterable"/>.
    /// </summary>
    [PublicAPI]
    public CssLineEdit FilterBox => _popup.FilterBox;

    /// <summary>
    /// Fired when the player chooses an item, also if it is the one that was already selected. It is not fired by
    /// <see cref="Select"/> and the like.
    /// </summary>
    [PublicAPI]
    public event Action<CssOptionSelectedEventArgs>? OnItemSelected;

    public CssOptionButton()
    {
        RobustXamlLoader.Load(this);

        ToggleMode = true;
        OnToggled += OnToggledInternal;

        _popup.Anchor = this;
        _popup.OnPopupHide += OnPopupHide;
        _popup.FilterBox.OnTextChanged += _ => UpdateFilters();
    }

    /// <summary>
    /// Adds an item to the end of the list. The first item added becomes selected.
    /// </summary>
    /// <param name="text">The text of the item, it is not markup.</param>
    /// <param name="value">What the item stands for, see <see cref="CssOptionItem.Value"/>.</param>
    [PublicAPI]
    public CssOptionItem AddItem(string text, object? value = null)
    {
        var item = new CssOptionItem(this, text, value);
        item.Button.AddCssStyleClass(CssClass.OptionItem);
        item.Button.CssStyleIdentifier = ItemCssStyleIdentifier;
        foreach (var styleClass in ItemCssStyleClasses)
        {
            item.Button.AddCssStyleClass(styleClass);
        }

        item.Button.OnPressed += _ => ItemPressed(item);
        _items.Add(item);
        _popup.ItemsBox.AddChild(item.Button);
        UpdateFilter(item);

        if (_items.Count == 1)
            Select(item);

        OnItemAdded(item);
        return item;
    }

    /// <summary>
    /// Called after an item was added, for overriding classes that restyle item buttons.
    /// </summary>
    protected virtual void OnItemAdded(CssOptionItem item) { }

    /// <summary>
    /// Removes the item. If it was selected, nothing is selected afterwards.
    /// </summary>
    [PublicAPI]
    public void RemoveItem(CssOptionItem item)
    {
        if (item.Owner != this)
            throw new ArgumentException("The item belongs to another button.", nameof(item));

        _items.Remove(item);
        _popup.ItemsBox.RemoveChild(item.Button);
        item.Owner = null;

        if (Selected == item)
        {
            Selected = null;
            UpdateLabel();
        }
    }

    /// <summary>
    /// Removes all items.
    /// </summary>
    [PublicAPI]
    public void Clear()
    {
        foreach (var item in _items)
        {
            item.Owner = null;
        }

        _items.Clear();
        _popup.ItemsBox.RemoveAllChildren();
        Selected = null;
        UpdateLabel();
    }

    /// <summary>
    /// Selects the item without firing <see cref="OnItemSelected"/>.
    /// </summary>
    [PublicAPI]
    public void Select(CssOptionItem item)
    {
        if (item.Owner != this)
            throw new ArgumentException("The item belongs to another button.", nameof(item));

        if (Selected != null)
            Selected.Button.Pressed = false;

        Selected = item;
        item.Button.Pressed = true;
        UpdateLabel();
    }

    /// <summary>
    /// Selects the first item whose <see cref="CssOptionItem.Value"/> equals <paramref name="value"/>, without
    /// firing <see cref="OnItemSelected"/>.
    /// </summary>
    /// <returns>false if there is no such item.</returns>
    [PublicAPI]
    public bool TrySelectValue(object? value)
    {
        var item = FindByValue(value);
        if (item == null)
            return false;

        Select(item);
        return true;
    }

    /// <summary>
    /// Same as <see cref="TrySelectValue"/>, but throws when there is no such item.
    /// </summary>
    [PublicAPI]
    public void SelectValue(object? value)
    {
        if (!TrySelectValue(value))
            throw new ArgumentException($"No item with the value {value}.", nameof(value));
    }

    /// <summary>
    /// The first item whose <see cref="CssOptionItem.Value"/> equals <paramref name="value"/>.
    /// </summary>
    [PublicAPI]
    public CssOptionItem? FindByValue(object? value)
        => _items.Find(item => Equals(item.Value, value));

    /// <summary>
    /// Opens the list of items.
    /// </summary>
    [PublicAPI]
    public void Open()
    {
        if (IsOpen)
            return;

        if (Root is not { } root)
            throw new InvalidOperationException("No UI root! We can't pop up!");

        var globalPos = GlobalPosition;
        globalPos.Y += Size.Y + 1; // Place it below us, with a safety margin.
        globalPos.Y -= Margin.SumVertical;

        _popup.Scroll.Measure(Window?.Size ?? Vector2Helpers.Infinity);
        var desired = _popup.Scroll.DesiredSize;
        var box = UIBox2.FromDimensions(globalPos, new Vector2(Math.Max(desired.X, Width), desired.Y));

        root.ModalRoot.AddChild(_popup);
        _popup.Open(box);
        Pressed = true;

        if (Filterable)
            _popup.FilterBox.GrabKeyboardFocus();
    }

    /// <summary>
    /// Closes the list of items.
    /// </summary>
    [PublicAPI]
    public void Close()
    {
        _popup.Close();
    }

    private void OnToggledInternal(CssButtonToggledEventArgs args)
    {
        // A press on the button doesn't close the list by itself (see CssOptionButtonPopup.Anchor), this does.
        if (args.Pressed)
            Open();
        else
            Close();
    }

    private void OnPopupHide()
    {
        _popup.Orphan();
        Pressed = false;
    }

    private void ItemPressed(CssOptionItem item)
    {
        Close();
        Select(item);
        OnItemSelected?.Invoke(new CssOptionSelectedEventArgs(this, item));
    }

    private void UpdateLabel()
    {
        var text = Selected?.Text ?? string.Empty;
        LabelControl.SetPlainText(Prefix.Length == 0 ? text : $"{Prefix} {text}");
    }

    internal void ItemTextChanged(CssOptionItem item)
    {
        if (Selected == item)
            UpdateLabel();

        UpdateFilter(item);
    }

    private void UpdateFilters()
    {
        foreach (var item in _items)
        {
            UpdateFilter(item);
        }
    }

    private void UpdateFilter(CssOptionItem item)
    {
        item.Button.Visible
            = !Filterable || item.Text.Contains(_popup.FilterBox.Text, StringComparison.CurrentCultureIgnoreCase);
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Close();
    }
}

/// <summary>
/// An item of a <see cref="CssOptionButton"/>.
/// </summary>
public sealed class CssOptionItem
{
    internal CssOptionButton? Owner;

    /// <summary>
    /// The button of the item in the list, for what <see cref="CssStyleClasses"/> and the like don't cover.
    /// </summary>
    public CssButton Button { get; }

    internal CssOptionItem(CssOptionButton owner, string text, object? value)
    {
        Owner = owner;
        Value = value;
        Button = new CssButton { ToggleMode = true };
        Text = text;
    }

    /// <summary>
    /// The button this item belongs to, <c>null</c> after it was removed.
    /// </summary>
    [PublicAPI]
    public CssOptionButton? Parent => Owner;

    /// <summary>
    /// What the item stands for. Not shown to the player.
    /// </summary>
    [PublicAPI]
    public object? Value { get; set; }

    /// <summary>
    /// The text of the item, it is not markup.
    /// </summary>
    [PublicAPI]
    public string Text
    {
        get;
        set
        {
            field = value;
            Button.SetPlainText(value);
            Owner?.ItemTextChanged(this);
        }
    }

    /// <summary>
    /// CSS style classes of the button of the item, in addition to <see cref="CssOptionButton.ItemCssStyleClasses"/>.
    /// </summary>
    public CssStyleClassCollection CssStyleClasses => Button.CssStyleClasses;

    /// <summary>
    /// CSS style identifier (<c>#id</c>) of the button of the item.
    /// </summary>
    public string? CssStyleIdentifier
    {
        get => Button.CssStyleIdentifier;
        set => Button.CssStyleIdentifier = value;
    }

    /// <summary>
    /// A disabled item can't be chosen.
    /// </summary>
    [PublicAPI]
    public bool Disabled
    {
        get => Button.Disabled;
        set => Button.Disabled = value;
    }

    [PublicAPI]
    public bool IsSelected => Owner?.Selected == this;

    /// <summary>
    /// <see cref="Value"/> as <typeparamref name="T"/>, <c>default</c> if it is of another type.
    /// </summary>
    [PublicAPI]
    public T? ValueAs<T>() => Value is T value ? value : default;
}

/// <summary>
/// Fired when the player chooses an item of a <see cref="CssOptionButton"/>.
/// </summary>
public sealed class CssOptionSelectedEventArgs(CssOptionButton button, CssOptionItem item) : EventArgs
{
    public CssOptionButton Button { get; } = button;

    public CssOptionItem Item { get; } = item;

    /// <summary>
    /// <see cref="CssOptionItem.Value"/> of the item.
    /// </summary>
    public object? Value => Item.Value;
}
