using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._RF.NPC.Components;
using Content.Shared._RF.NPC.Systems;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._RF.UserInterface.Controls.NpcJobs;

[GenerateTypedNameReferences]
public sealed partial class NpcJobsSettingsWindow : FancyWindow
{
    [Dependency] private readonly IEntityManager _entity = default!;
    [Dependency] private readonly IPlayerManager _player = default!;
    [Dependency] private readonly IPrototypeManager _proto = default!;

    private NpcJobsSystem _npcJobs = default!;

    private readonly HashSet<NpcJobButton> _dirtyButtons = new();
    private readonly HashSet<int> _deleteJobs = new();
    private readonly ButtonGroup _jobButtonGroup = new();

    private int? _selectedJob;

    public NpcJobsSettingsWindow()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        SaveButton.OnPressed += _ =>
        {
            if (_player.LocalEntity is not { } uid)
                return;

            foreach (var button in _dirtyButtons)
            {
                var icon = button.Icon.CurrentTexturePath is { } path ? new SpriteSpecifier.Texture(new(path)) : null;

                if (button.JobId == 0)
                    _npcJobs.CreateJob(uid, button.JobName, icon, button.Goals);
                else
                    _npcJobs.UpdateJob(uid, button.JobId, button.JobName, icon, button.Goals ?? new());
            }

            foreach (var id in _deleteJobs)
            {
                if (id != 0)
                    _npcJobs.DeleteJob(uid, id);
            }

            _dirtyButtons.Clear();
            _deleteJobs.Clear();

            SaveButton.Disabled = true;
        };

        CreateRoleButton.OnPressed += _ =>
        {
            var button = new NpcJobButton();
            var locName = Loc.GetString("new-npc-job-name");
            var sameCount = JobsContainer.Children.Count(x => x is NpcJobButton b && b.JobName.StartsWith(locName));

            button.JobName = sameCount > 0 ? $"{locName} {sameCount + 1}" : locName;

            _dirtyButtons.Add(button);
            SaveButton.Disabled = false;
            AddJobButton(button);
        };
    }

    public void EnsureSetup()
    {
        _npcJobs = _entity.System<NpcJobsSystem>();
        _npcJobs.OnJobChanged += _ => Build();

        Build();
    }

    public void Build()
    {
        JobsContainer.RemoveAllChildren();
        TasksContainer.RemoveAllChildren();

        _dirtyButtons.Clear();
        _deleteJobs.Clear();

        SaveButton.Disabled = true;

        if (!_entity.TryGetComponent(_player.LocalEntity, out NpcJobsComponent? comp))
            return;

        foreach (var job in comp.Jobs)
        {
            var button = new NpcJobButton(job);
            AddJobButton(button);
        }
    }

    private void BuildTasks(NpcJobButton button)
    {
        TasksContainer.RemoveAllChildren();

        if (!_entity.TryGetComponent(_player.LocalEntity, out NpcJobsComponent? comp)
            || !_npcJobs.TryGetJob(button.JobId, out var job))
            return;

        var goals = button.Goals ?? job.Goals;
        var sortedTasks = comp.AccessibleGoals
            .Select(x => _proto.Index(x))
            .OrderBy(x => x.Name);

        foreach (var task in sortedTasks)
        {
            var taskButton = new NpcTaskButton(task);
            taskButton.CheckBox.Pressed = goals.Contains(task);

            taskButton.CheckBox.OnPressed += _ =>
            {
                button.Goals ??= _npcJobs.TryGetJob(button.JobId, out var j) ? j.Goals : new();

                if (taskButton.CheckBox.Pressed)
                    button.Goals.Add(task);
                else
                    button.Goals.Remove(task);

                _dirtyButtons.Add(button);
                SaveButton.Disabled = false;
            };

            TasksContainer.AddChild(taskButton);
        }
    }

    private void AddJobButton(NpcJobButton button)
    {
        button.Group = _jobButtonGroup;
        button.Pressed = button.JobId == _selectedJob;

        if (button.Pressed)
            BuildTasks(button);

        button.OnDataChanged += () =>
        {
            _dirtyButtons.Add(button);
            SaveButton.Disabled = false;
        };

        button.OnDeleted += () =>
        {
            _dirtyButtons.Remove(button);
            _deleteJobs.Add(button.JobId);
            SaveButton.Disabled = false;
        };

        button.OnPressed += _ =>
        {
            _selectedJob = button.JobId;
            BuildTasks(button);
        };

        JobsContainer.AddChild(button);
    }
}

