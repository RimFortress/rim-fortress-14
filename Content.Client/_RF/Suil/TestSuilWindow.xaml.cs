using System.Linq;
using JetBrains.Annotations;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Console;

namespace Content.Client._RF.Suil;

[GenerateTypedNameReferences]
public sealed partial class TestSuilWindow : DefaultWindow
{
    public TestSuilWindow()
    {
        RobustXamlLoader.Load(this);

        IdEdit.OnTextEntered += args => TestControl.SuilStyleIdentifier = args.Text;
        StyleEdit.OnTextEntered += args =>
        {
            TestControl.SuilStyleClasses = SuilStyleClassCollection.Parse(args.Text);
            TestControl.DoStyleUpdate();
        };

        PseudoEdit.OnTextEntered += args => TestControl.SuilPseudoStyleClasses = SuilStyleClassCollection.Parse(args.Text);

        ReloadButton.OnPressed += _ => IoCManager
            .Resolve<IConsoleHost>()
            .ExecuteCommand("rldsuil");
    }
}

public sealed class TestSuilWindowControl : UiElement;

[UsedImplicitly]
public sealed class SuilDebugCommand : IConsoleCommand
{
    public string Command => "suil_debug";
    public string Description => "";
    public string Help => "";

    public void Execute(IConsoleShell shell, string argStr, string[] args)
    {
        new TestSuilWindow().OpenCentered();
    }
}
