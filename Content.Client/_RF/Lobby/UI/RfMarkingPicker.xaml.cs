using Content.Client._RF.UserInterface.Controls;
using Content.Client.Humanoid;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._RF.Lobby.UI;

/// <summary>
/// The picker of the markings of a character, the <see cref="RfBoxContainer"/> version of
/// <see cref="MarkingPicker"/>: a tab for every organ that has markings, in every one the
/// <see cref="RfOrganMarkingPicker"/>.
/// </summary>
/// <remarks>
/// The tabs are <see cref="RfTabContainer"/>s (<c>.marking-tabs</c>), the layout is in <c>RfMarkingPicker.xaml</c>,
/// the styles are in <c>Resources/UI/_RF/lobby/markings.suil</c>.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class RfMarkingPicker : RfBoxContainer
{
    private MarkingsViewModel? _markingsModel;
    private bool _dirty = true;

    public RfMarkingPicker()
    {
        RobustXamlLoader.Load(this);
    }

    public void SetModel(MarkingsViewModel model)
    {
        _markingsModel = model;
        _dirty = true;

        Subscribe();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        Subscribe();
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        Unsubscribe();
    }

    private void Subscribe()
    {
        if (_markingsModel is not { } model)
            return;

        // Not twice if the model was set while the picker is in the tree.
        Unsubscribe();
        model.OrganDataChanged += Invalidate;
        model.EnforcementsChanged += Invalidate;
        model.OrganProfileDataChanged += OnOrganProfileDataChanged;
    }

    private void Unsubscribe()
    {
        if (_markingsModel is not { } model)
            return;

        model.OrganDataChanged -= Invalidate;
        model.EnforcementsChanged -= Invalidate;
        model.OrganProfileDataChanged -= OnOrganProfileDataChanged;
    }

    // The organs can be empty for the sex or the species the profile data has not caught up with yet, so a change of
    // the set of the markings possible rebuilds the pickers, as the change of the organs does.
    private void OnOrganProfileDataChanged(bool refresh)
    {
        if (refresh)
            Invalidate();
    }

    // The model changes in several steps (the organs, then their profile data, then the markings): the pickers are
    // rebuilt once, in the next frame, and only while they are shown.
    private void Invalidate()
    {
        _dirty = true;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        if (!_dirty)
            return;

        _dirty = false;
        UpdateMarkings();
    }

    private void UpdateMarkings()
    {
        if (_markingsModel is null)
            return;

        OrganTabs.Clear();

        foreach (var (organ, organData) in _markingsModel.OrganData)
        {
            var control = new RfOrganMarkingPicker(_markingsModel, organ, organData.Layers, organData.Group);
            if (control.Empty)
                continue;

            OrganTabs.AddTab(Loc.GetString($"markings-organ-{organ.Id}"), control);
        }

        OrganTabs.TabBarVisible = OrganTabs.Tabs.Count > 1;
    }
}
