using Content.Suil;
using Content.Client._RF.UserInterface.Controls;
using Content.Client.Humanoid;
using Content.Shared.Body;
using Content.Shared.Humanoid;
using Content.Shared.Humanoid.Markings;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._RF.Lobby.UI;

/// <summary>
/// The markings of one organ: a tab for every layer that has markings, in every one the
/// <see cref="RfLayerMarkingPicker"/>. The <see cref="RfBoxContainer"/> version of <see cref="OrganMarkingPicker"/>.
/// </summary>
[GenerateTypedNameReferences]
[SuilTag("organ-marking-picker")]
public sealed partial class RfOrganMarkingPicker : RfBoxContainer
{
    [Dependency] private MarkingManager _marking = default!;

    private readonly MarkingsViewModel _markingsModel;
    private readonly HashSet<HumanoidVisualLayers> _layers;
    private readonly ProtoId<MarkingsGroupPrototype> _group;
    private readonly ProtoId<OrganCategoryPrototype> _organ;

    public RfOrganMarkingPicker(
        MarkingsViewModel markingsModel,
        ProtoId<OrganCategoryPrototype> organ,
        HashSet<HumanoidVisualLayers> layers,
        ProtoId<MarkingsGroupPrototype> group)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _markingsModel = markingsModel;
        _layers = layers;
        _group = group;
        _organ = organ;

        UpdateMarkings();
    }

    /// <summary>
    /// There are no markings to choose on any layer of the organ.
    /// </summary>
    public bool Empty => LayerTabs.Tabs.Count == 0;

    private void UpdateMarkings()
    {
        if (!_markingsModel.OrganProfileData.TryGetValue(_organ, out var organProfileData))
            return;

        LayerTabs.Clear();

        foreach (var layer in _layers)
        {
            var allMarkings = _markingsModel.EnforceGroupAndSexRestrictions
                ? _marking.MarkingsByLayerAndGroupAndSex(layer, _group, organProfileData.Sex)
                : _marking.MarkingsByLayer(layer);

            if (allMarkings.Count == 0)
                continue;

            var title = Loc.TryGetString($"markings-layer-{layer}-{_group.Id}", out var layerTitle)
                ? layerTitle
                : Loc.GetString($"markings-layer-{layer}");

            LayerTabs.AddTab(title, new RfLayerMarkingPicker(_markingsModel, _organ, layer, allMarkings));
        }

        LayerTabs.TabBarVisible = LayerTabs.Tabs.Count > 1;
    }
}
