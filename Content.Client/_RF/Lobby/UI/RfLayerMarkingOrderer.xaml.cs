/// <summary>
/// The selected markings of a layer in their order, which the player changes by dragging a marking between the
/// others. The <see cref="RfBoxContainer"/> version of <see cref="LayerMarkingOrderer"/>.
/// </summary>
/// <remarks>
/// A marking is in an <c>.marking-item-slot</c>, between the <c>.marking-drop-beacon</c>s; the beacon that the
/// marking would be dropped on gets <c>.drop-target</c>.
/// </remarks>
[GenerateTypedNameReferences]
public sealed partial class RfLayerMarkingOrderer : RfBoxContainer
{
    private const float ItemHeight = 64f;

    private readonly ProtoId<OrganCategoryPrototype> _organ;
    private readonly HumanoidVisualLayers _layer;
    private readonly MarkingsViewModel _markingsModel;
    private readonly DragDropHelper<RfLayerMarkingDragged> _dragDropHelper;
    private readonly List<RfLayerDragDropBeacon> _beacons = new();
    private RfLayerDragDropBeacon? _dragTarget;

    [Dependency] private IPrototypeManager _prototype = default!;

    public RfLayerMarkingOrderer(MarkingsViewModel markingsModel, ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _markingsModel = markingsModel;
        _organ = organ;
        _layer = layer;
        _dragDropHelper = new(OnBeginDrag, OnContinueDrag, OnEndDrag);

        UpdateItems();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();

        _markingsModel.MarkingsReset += UpdateItems;
        _markingsModel.MarkingsChanged += MarkingsChanged;
    }

    protected override void ExitedTree()
    {
        base.ExitedTree();

        _markingsModel.MarkingsReset -= UpdateItems;
        _markingsModel.MarkingsChanged -= MarkingsChanged;
    }

    private void MarkingsChanged(ProtoId<OrganCategoryPrototype> organ, HumanoidVisualLayers layer)
    {
        if (_organ != organ || _layer != layer)
            return;

        UpdateItems();
    }

    private void UpdateItems()
    {
        Items.RemoveAllChildren();
        _beacons.Clear();

        if (_markingsModel.SelectedMarkings(_organ, _layer) is not { } markings)
            return;

        for (var idx = 0; idx < markings.Count; idx++)
        {
            var marking = markings[idx];

            var container = new RfLayerMarkingItemSlot();

            var item = new RfLayerMarkingItem(_markingsModel, _organ, _layer, _prototype.Index<MarkingPrototype>(marking.MarkingId), false);
            item.DefaultCursorShape = CursorShape.Hand;
            item.Pressed += (_, control) => _dragDropHelper.MouseDown(new(control, container));
            item.Unpressed += (_, _) => _dragDropHelper.EndDrag();

            container.AddChild(item);

            var before = new RfLayerDragDropBeacon(CandidatePosition.Before, idx);
            var after = new RfLayerDragDropBeacon(CandidatePosition.After, idx);
            _beacons.Add(before);
            _beacons.Add(after);

            Items.AddChild(before);
            Items.AddChild(container);
            Items.AddChild(after);
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);

        _dragDropHelper.Update(args.DeltaSeconds);
    }

    private bool OnBeginDrag()
    {
        var (item, container) = _dragDropHelper.Dragged;

        container.Visible = false;
        item.Orphan();
        item.DefaultCursorShape = CursorShape.Move;
        UserInterfaceManager.PopupRoot.AddChild(item);
        LayoutContainer.SetPosition(item, UserInterfaceManager.MousePositionScaled.Position - new Vector2(32, 32));
        return true;
    }

    private bool OnContinueDrag(float frameTime)
    {
        var (item, _) = _dragDropHelper.Dragged;

        LayoutContainer.SetPosition(item, UserInterfaceManager.MousePositionScaled.Position - new Vector2(32, 32));

        var closestBeacon = _beacons.MinBy(beacon =>
            (UserInterfaceManager.MousePositionScaled.Position - beacon.GlobalPosition).LengthSquared());

        if (closestBeacon != _dragTarget)
        {
            _dragTarget?.UnbecomeTarget();
            _dragTarget = closestBeacon;
            _dragTarget?.BecomeTarget(ItemHeight);
        }

        return true;
    }

    private void OnEndDrag()
    {
        var (item, container) = _dragDropHelper.Dragged;

        container.Visible = true;
        item.Orphan();
        container.AddChild(item);
        _dragTarget?.UnbecomeTarget();

        if (_dragTarget != null)
            _markingsModel.ChangeMarkingOrder(_organ, _layer, item.MarkingId, _dragTarget.CandidatePosition, _dragTarget.Index);
    }
}

internal readonly record struct RfLayerMarkingDragged(RfLayerMarkingItem Item, RfLayerMarkingItemSlot Container);

internal sealed class RfLayerMarkingItemSlot : UiElement
{
    public RfLayerMarkingItemSlot()
    {
        SetHeight = 64;
        AddSuilStyleClass("marking-item-slot");
    }
}

internal sealed class RfLayerDragDropBeacon : UiElement
{
    public readonly CandidatePosition CandidatePosition;
    public readonly int Index;

    public RfLayerDragDropBeacon(CandidatePosition position, int index)
    {
        CandidatePosition = position;
        Index = index;
        AddSuilStyleClass("marking-drop-beacon");
    }

    public void BecomeTarget(float height)
    {
        SetHeight = height;
        AddSuilStyleClass("drop-target");
    }

    public void UnbecomeTarget()
    {
        SetHeight = float.NaN;
        RemoveSuilStyleClass("drop-target");
    }
}
