using System.Linq;
using Content.Client._RF.NPC.UI;
using Content.Shared._RF.NPC;
using Content.Shared._RF.NPC.UtilityAi;
using Content.Shared.Input;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._RF.NPC.UtilityAi.UI;

[GenerateTypedNameReferences]
public sealed partial class UtilityAiDebugTab : AiDevWindowTab
{
    private UtilityAiDebugInfo? _info;

    public UtilityAiDebugTab()
    {
        RobustXamlLoader.Load(this);
    }

    public void Update(UtilityAiDebugInfo info)
    {
        var firstUpdate = Layout == null;
        UnExpandNode();
        NodeControls.Clear();
        _info = info;

        GraphRoot.RemoveAllChildren();
        Layout = GraphLayoutBuilder.Build(info.Graph, NodeSize);

        foreach (var node in info.Graph.Nodes)
        {
            var control = new UtilityAiGoalControl(node, info.CurrentGoal);
            control.OnKeyBindUp += args =>
            {
                if (args.Function == ContentKeyFunctions.MouseMiddle)
                    ToggleExpanded(node.Id);
            };

            GraphRoot.AddChild(control);
            NodeControls[node.Id] = control;
        }

        UpdateLayout();

        if (firstUpdate)
            ScrollContainer.SetScrollValue(Layout.Value.TotalSize / 2);
    }

    protected override void OnUpdateLayout(GraphLayout layout)
    {
        EdgeOverlay.SetData(
            NodeControls,
            layout.EdgePaths,
            layout.EdgePaths
                .Select(xy => (xy.Key, ConnectionColor(xy.Key)))
                .ToDictionary());

        return;

        Color ConnectionColor((int From, int To) fromTo)
        {
            if (_info?.Graph.Nodes.Any(x => x.Id == fromTo.From && x.InActiveBranch) == true)
                return Color.LimeGreen;

            return Color.DimGray; // Default color
        }
    }

    protected override void KeyBindUp(GUIBoundKeyEventArgs args)
    {
        base.KeyBindUp(args);

        if (args.Function != ContentKeyFunctions.TextFind)
            return;

        SearchPanel.Expanded = true;
        UserInterfaceManager.GrabKeyboardFocus(Search);
    }
}

