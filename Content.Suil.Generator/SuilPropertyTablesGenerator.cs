using System.Text;
using Microsoft.CodeAnalysis;

namespace Content.Suil.Generator;

/// <summary>
/// Writes <c>Content.Suil.SuilPropertyTables.Register(SuilPropertyRegistry)</c>: the accessors of every public
/// settable property and field of every UI control, the ones of the project and the ones of the engine and the game
/// (the <c>Content</c> and <c>Robust</c> namespaces). The runtime can't find them with reflection, and the engine
/// classes can't be marked, so nothing needs a mark: <see cref="SuilPropertyAttribute"/> only changes the name,
/// the parser and the inheritance of a member. The exception is a member that is not public: the table can't reach it,
/// so one with the attribute is registered from the class itself (it must be partial), see <c>SuilAddProperties</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SuilPropertyTablesGenerator : IIncrementalGenerator
{
    private const string ControlName = "Robust.Client.UserInterface.Control";
    private const string TablesInterfaceName = "Content.Suil.ISuilControlTables";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // A project describes the controls it declares itself. Only the game also takes the ones of the engine and of the
        // other assemblies it references (build property SuilIncludeReferencedControls), so no type has two tables.
        var includeReferenced = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
            options.GlobalOptions.TryGetValue("build_property.SuilIncludeReferencedControls", out var value)
            && value.Equals("true", StringComparison.OrdinalIgnoreCase));

        var source = context.CompilationProvider
            .Combine(includeReferenced)
            .Select(static (pair, ct) => Build(pair.Left, pair.Right, ct));

        context.RegisterSourceOutput(source, static (ctx, text) =>
        {
            if (text != null)
                ctx.AddSource("SuilPropertyTables.g.cs", text);
        });
    }

    private static string? Build(Compilation compilation, bool includeReferenced, CancellationToken cancellationToken)
    {
        var control = compilation.GetTypeByMetadataName(ControlName);

        // a project without the UI (the server, the shared code) has nothing to write
        if (control == null || compilation.GetTypeByMetadataName(TablesInterfaceName) == null)
            return null;

        var types = new List<INamedTypeSymbol>();
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);

        void Visit(INamespaceSymbol ns)
        {
            cancellationToken.ThrowIfCancellationRequested();

            foreach (var member in ns.GetMembers())
            {
                switch (member)
                {
                    case INamespaceSymbol child:
                        Visit(child);
                        break;
                    case INamedTypeSymbol type:
                        VisitType(type);
                        break;
                }
            }
        }

        void VisitType(INamedTypeSymbol type)
        {
            if (IsControl(type, control, compilation) && seen.Add(type))
                types.Add(type);

            foreach (var nested in type.GetTypeMembers())
            {
                VisitType(nested);
            }
        }

        Visit(compilation.Assembly.GlobalNamespace);

        if (includeReferenced)
        {
            foreach (var root in compilation.GlobalNamespace.GetNamespaceMembers())
            {
                if (root.Name is "Content" or "Robust")
                    Visit(root);
            }
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// The SUIL accessors of the public members of the controls. Don't edit.");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine("#nullable disable");
        sb.AppendLine("#pragma warning disable");
        sb.AppendLine();
        // one class per assembly: the tables of every assembly the generator runs on are found by the interface
        var className = "SuilPropertyTables_" + new string((compilation.AssemblyName ?? "Assembly")
            .Select(c => char.IsLetterOrDigit(c) ? c : '_').ToArray());

        sb.AppendLine("namespace Content.Suil");
        sb.AppendLine("{");
        sb.AppendLine($"    public sealed class {className} : global::Content.Suil.ISuilControlTables");
        sb.AppendLine("    {");
        sb.AppendLine("        public void RegisterProperties(global::Content.Suil.SuilPropertyRegistry registry)");
        sb.AppendLine("        {");

        var partials = new StringBuilder();
        var shorthandTypes = new List<(INamedTypeSymbol Type, List<ShorthandGroup> Groups, bool InPartial)>();
        var eventTypes = new List<(INamedTypeSymbol Type, List<EventMember> Events)>();
        var argumentTypes = new Dictionary<string, INamedTypeSymbol>(StringComparer.Ordinal);

        foreach (var type in types.OrderBy(t => t.ToDisplayString(), StringComparer.Ordinal))
        {
            var members = Members(type, compilation, out var hidden);
            var hasHidden = hidden.Count > 0 && IsPartialChain(type);

            // The shorthands are described by the members of the class; a class that is partial gets a method with the
            // table, so the parsers that are private can be named in it.
            var groups = Shorthands(type, compilation);
            var shorthandsInPartial = groups.Count > 0 && IsPartialChain(type);

            if (groups.Count > 0)
                shorthandTypes.Add((type, groups, shorthandsInPartial));

            var events = Events(type, compilation);

            if (events.Count > 0)
            {
                eventTypes.Add((type, events));

                foreach (var evt in events)
                {
                    if (evt.Argument != null)
                        argumentTypes[evt.Argument.ToDisplayString(Format)] = evt.Argument;
                }
            }

            if (hasHidden || shorthandsInPartial)
                WritePartial(partials, type, hasHidden ? hidden : new List<Member>(), shorthandsInPartial ? groups : null);

            if (members.Count == 0 && !hasHidden)
                continue;

            var typeName = type.ToDisplayString(Format);
            sb.AppendLine($"            registry.Register(typeof({typeName}), static () =>");
            sb.AppendLine("            {");
            sb.AppendLine("                var table = new global::System.Collections.Generic.Dictionary<string, global::Content.Suil.SuilPropertyAccessor>();");

            foreach (var member in members)
            {
                WriteAccessor(sb, "                ", "table", typeName, member);
            }

            if (hasHidden)
                sb.AppendLine($"                {typeName}.SuilAddProperties(table);");

            sb.AppendLine("                return table;");
            sb.AppendLine("            });");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public void RegisterShorthands(global::Content.Suil.SuilShorthandTable shorthands)");
        sb.AppendLine("        {");

        foreach (var (type, groups, inPartial) in shorthandTypes)
        {
            var typeName = type.ToDisplayString(Format);

            if (inPartial)
            {
                sb.AppendLine($"            shorthands.Add(typeof({typeName}), {typeName}.SuilShorthands());");
                continue;
            }

            sb.AppendLine("            {");
            WriteShorthandTable(sb, "                ", typeName, groups, "shorthands.Add(typeof(" + typeName + "), table);");
            sb.AppendLine("            }");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public void RegisterEvents(global::Content.Suil.SuilEventTable events)");
        sb.AppendLine("        {");

        foreach (var (type, list) in eventTypes)
        {
            var typeName = type.ToDisplayString(Format);
            sb.AppendLine($"            events.Add(typeof({typeName}), new global::System.Collections.Generic.Dictionary<string, global::Content.Suil.SuilEventAccessor>");
            sb.AppendLine("            {");

            foreach (var evt in list)
            {
                WriteEventAccessor(sb, "                ", typeName, evt);
            }

            sb.AppendLine("            });");
        }

        foreach (var pair in argumentTypes.OrderBy(p => p.Key, StringComparer.Ordinal))
        {
            var name = pair.Key;
            var flags = Flags(pair.Value);

            if (flags.Count == 0)
                continue;

            sb.AppendLine($"            events.AddArguments(typeof({name}), new global::System.Collections.Generic.Dictionary<string, global::System.Func<object, bool>>");
            sb.AppendLine("            {");

            foreach (var (flag, member) in flags)
            {
                sb.AppendLine($"                [{Literal(flag)}] = static o => (({name}) o).{member},");
            }

            sb.AppendLine("            });");
        }

        sb.AppendLine("        }");
        sb.AppendLine();
        sb.AppendLine("        public void RegisterTags(global::Content.Suil.SuilTagTable tags)");
        sb.AppendLine("        {");

        // the project describes its own controls; the game also the ones it references
        var owner = includeReferenced ? null : compilation.Assembly;
        var registry = SuilTagRegistry.Build(CollectTagRegistrations(compilation, types), control, compilation, _ => { });

        foreach (var (tag, type) in registry.Entries(owner)
                     .OrderBy(e => e.Tag, StringComparer.Ordinal)
                     .ThenBy(e => e.Type.ToDisplayString(), StringComparer.Ordinal))
        {
            sb.AppendLine($"            tags.Add({Literal(tag)}, typeof({type.ToDisplayString(Format)}));");
        }

        sb.AppendLine("        }");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.Append(partials);
        return sb.ToString();
    }

    private static readonly SymbolDisplayFormat Format = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(
            SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions
            & ~SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static bool IsControl(INamedTypeSymbol type, INamedTypeSymbol control, Compilation compilation)
    {
        return type.TypeKind == TypeKind.Class
               && !type.IsStatic
               && type.TypeParameters.Length == 0
               && !IsObsolete(type)
               && compilation.IsSymbolAccessibleWithin(type, compilation.Assembly)
               && SuilTagRegistry.Derives(type, control);
    }

    /// <summary>
    /// The custom tags: [SuilTag] on the assembly and on the classes.
    /// </summary>
    private static List<SuilTagRegistration> CollectTagRegistrations(Compilation compilation, List<INamedTypeSymbol> types)
    {
        var result = new List<SuilTagRegistration>();

        foreach (var attribute in compilation.Assembly.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString() != SuilViewAttributeSource.TagMetadataName)
                continue;

            if (attribute.ConstructorArguments is [{ Value: string name }, { Value: INamedTypeSymbol type }])
                result.Add(new SuilTagRegistration(name, type, Location.None));
        }

        foreach (var type in types)
        {
            foreach (var attribute in type.GetAttributes())
            {
                switch (attribute.AttributeClass?.ToDisplayString())
                {
                    case SuilViewAttributeSource.TagMetadataName
                        when attribute.ConstructorArguments is [{ Value: string tag }]:
                        result.Add(new SuilTagRegistration(tag, type, Location.None));
                        break;
                }
            }
        }

        return result;
    }

    private sealed record Member(string Name, string MemberName, string TypeName, string? Parser, bool Inherited, bool CanRead);

    private static void WriteAccessor(StringBuilder sb, string indent, string table, string typeName, Member member)
    {
        sb.AppendLine($"{indent}{table}[{Literal(member.Name)}] = new global::Content.Suil.SuilPropertyAccessor(");
        sb.AppendLine($"{indent}    {Literal(member.Name)}, {Literal(member.MemberName)}, typeof({member.TypeName}),");
        sb.AppendLine($"{indent}    static (c, v) => (({typeName}) c).{member.MemberName} = ({member.TypeName}) v,");
        sb.AppendLine(member.CanRead
            ? $"{indent}    static c => (object) (({typeName}) c).{member.MemberName},"
            : $"{indent}    null,");
        sb.AppendLine($"{indent}    {(member.Parser == null ? "null" : $"typeof({member.Parser})")}, {(member.Inherited ? "true" : "false")});");
    }

    /// <summary>
    /// Whether the type and everything it is nested in is a partial class, so a part can be added to it.
    /// </summary>
    private static bool IsPartialChain(INamedTypeSymbol type)
    {
        for (var current = type; current != null; current = current.ContainingType)
        {
            if (current.TypeKind != TypeKind.Class || current.TypeParameters.Length > 0)
                return false;

            foreach (var reference in current.DeclaringSyntaxReferences)
            {
                if (reference.GetSyntax() is not Microsoft.CodeAnalysis.CSharp.Syntax.ClassDeclarationSyntax syntax
                    || !syntax.Modifiers.Any(m => m.Text == "partial"))
                {
                    return false;
                }
            }

            if (current.DeclaringSyntaxReferences.Length == 0)
                return false;
        }

        return true;
    }

    /// <summary>
    /// Adds a part to the class with the accessors of its members that are not public, and with the table of its
    /// shorthands.
    /// </summary>
    private static void WritePartial(StringBuilder sb, INamedTypeSymbol type, List<Member> hidden, List<ShorthandGroup>? shorthands)
    {
        var typeName = type.ToDisplayString(Format);
        var containers = new List<INamedTypeSymbol>();
        for (var current = type; current != null; current = current.ContainingType)
        {
            containers.Insert(0, current);
        }

        var ns = type.ContainingNamespace;
        var hasNamespace = ns is { IsGlobalNamespace: false };

        if (hasNamespace)
        {
            sb.AppendLine($"namespace {ns.ToDisplayString()}");
            sb.AppendLine("{");
        }

        foreach (var container in containers)
        {
            sb.AppendLine($"    partial class {container.Name}");
            sb.AppendLine("    {");
        }

        if (hidden.Count > 0)
        {
            sb.AppendLine("        internal static void SuilAddProperties(global::System.Collections.Generic.Dictionary<string, global::Content.Suil.SuilPropertyAccessor> table)");
            sb.AppendLine("        {");

            foreach (var member in hidden)
            {
                WriteAccessor(sb, "            ", "table", typeName, member);
            }

            sb.AppendLine("        }");
        }

        if (shorthands != null)
        {
            sb.AppendLine("        internal static global::System.Collections.Generic.Dictionary<string, global::Content.Suil.SuilShorthandInfo> SuilShorthands()");
            sb.AppendLine("        {");
            WriteShorthandTable(sb, "            ", typeName, shorthands, "return table;");
            sb.AppendLine("        }");
        }

        foreach (var _ in containers)
        {
            sb.AppendLine("    }");
        }

        if (hasNamespace)
            sb.AppendLine("}");
    }

    // ---- Events ----

    private sealed record EventMember(string Name, string MemberName, string DelegateName, INamedTypeSymbol? Argument);

    /// <summary>
    /// The public instance events the type declares that a handler of a file can subscribe to: the delegate returns
    /// nothing and takes nothing or one argument.
    /// </summary>
    private static List<EventMember> Events(INamedTypeSymbol type, Compilation compilation)
    {
        var result = new List<EventMember>();

        foreach (var member in type.GetMembers())
        {
            if (member is not IEventSymbol { IsStatic: false, DeclaredAccessibility: Accessibility.Public } evt
                || IsObsolete(evt)
                || evt.Type is not INamedTypeSymbol { DelegateInvokeMethod: { } invoke } delegateType
                || !invoke.ReturnsVoid
                || invoke.Parameters.Length > 1
                || invoke.Parameters.Any(p => p.RefKind != RefKind.None))
            {
                continue;
            }

            INamedTypeSymbol? argument = null;

            if (invoke.Parameters.Length == 1)
            {
                // a pointer, a type parameter or an inaccessible type can't be named in the table
                if (invoke.Parameters[0].Type is not INamedTypeSymbol named
                    || named.TypeParameters.Length > 0 && named.IsUnboundGenericType
                    || !compilation.IsSymbolAccessibleWithin(named, compilation.Assembly))
                {
                    continue;
                }

                argument = named;
            }

            result.Add(new EventMember(
                SuilNaming.ToKebab(evt.Name),
                evt.Name,
                delegateType.ToDisplayString(Format),
                argument));
        }

        return result;
    }

    private static void WriteEventAccessor(StringBuilder sb, string indent, string typeName, EventMember evt)
    {
        var argument = evt.Argument == null ? "null" : $"typeof({evt.Argument.ToDisplayString(Format)})";
        var lambda = evt.Argument == null ? "() => handler(null)" : "argument => handler(argument)";

        sb.AppendLine($"{indent}[{Literal(evt.Name)}] = new global::Content.Suil.SuilEventAccessor(");
        sb.AppendLine($"{indent}    {Literal(evt.Name)}, {Literal(evt.MemberName)}, {argument},");
        sb.AppendLine($"{indent}    static (control, handler) =>");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        {evt.DelegateName} added = {lambda};");
        sb.AppendLine($"{indent}        (({typeName}) control).{evt.MemberName} += added;");
        sb.AppendLine($"{indent}        return added;");
        sb.AppendLine($"{indent}    }},");
        sb.AppendLine($"{indent}    static (control, added) => (({typeName}) control).{evt.MemberName} -= ({evt.DelegateName}) added),");
    }

    /// <summary>
    /// The public bool members of an arguments type by their names in SUIL: what <c>args.pressed</c> can read.
    /// </summary>
    private static List<(string Name, string Member)> Flags(INamedTypeSymbol argument)
    {
        var result = new List<(string, string)>();
        var seen = new HashSet<string>(StringComparer.Ordinal);

        for (INamedTypeSymbol? current = argument; current != null; current = current.BaseType)
        {
            foreach (var member in current.GetMembers())
            {
                if (member.IsStatic || member.DeclaredAccessibility != Accessibility.Public)
                    continue;

                var type = member switch
                {
                    IPropertySymbol { IsIndexer: false, GetMethod: { DeclaredAccessibility: Accessibility.Public } } p => p.Type,
                    IFieldSymbol f => f.Type,
                    _ => null,
                };

                if (type?.SpecialType == SpecialType.System_Boolean && seen.Add(member.Name))
                    result.Add((SuilNaming.ToKebab(member.Name), member.Name));
            }
        }

        return result;
    }

    private sealed record ShorthandMember(string SuilName, string TypeName, string? ParserMethod);

    private sealed record ShorthandGroup(string Name, List<ShorthandMember> Members, string? ParserMethod);

    /// <summary>
    /// The shorthands the members of the class belong to, by [SuilShorthand]: a member can be in several, and a group
    /// can have one parser method named by any of its members.
    /// </summary>
    private static List<ShorthandGroup> Shorthands(INamedTypeSymbol type, Compilation compilation)
    {
        var groups = new List<ShorthandGroup>();
        var byName = new Dictionary<string, List<ShorthandMember>>(StringComparer.Ordinal);
        var order = new List<string>();
        var partial = IsPartialChain(type);

        foreach (var symbol in type.GetMembers())
        {
            ITypeSymbol valueType;

            switch (symbol)
            {
                case IPropertySymbol { IsStatic: false, IsIndexer: false } property:
                    valueType = property.Type;
                    break;
                case IFieldSymbol { IsStatic: false, IsImplicitlyDeclared: false } field:
                    valueType = field.Type;
                    break;
                default:
                    continue;
            }

            var attributes = symbol.GetAttributes()
                .Where(a => a.AttributeClass?.ToDisplayString() == SuilViewAttributeSource.ShorthandMetadataName)
                .ToList();

            if (attributes.Count == 0)
                continue;

            var name = SuilNaming.ToKebab(symbol.Name);
            var propertyAttribute = symbol.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == SuilViewAttributeSource.PropertyMetadataName);

            if (propertyAttribute is { ConstructorArguments.Length: > 0 } && propertyAttribute.ConstructorArguments[0].Value is string custom)
                name = custom;

            foreach (var attribute in attributes)
            {
                if (attribute.ConstructorArguments.Length == 0 || attribute.ConstructorArguments[0].Value is not string shorthand)
                    continue;

                // a method that is missing, or is not the right shape, is the same as no method: the generated expander
                var method = attribute.ConstructorArguments.Length > 1
                             && attribute.ConstructorArguments[1].Value is string methodName
                             && HasParserMethod(type, methodName, partial, compilation)
                    ? methodName
                    : null;

                if (!byName.TryGetValue(shorthand, out var members))
                {
                    byName[shorthand] = members = new List<ShorthandMember>();
                    order.Add(shorthand);
                }

                members.Add(new ShorthandMember(name, valueType.ToDisplayString(Format), method));
            }
        }

        foreach (var shorthand in order)
        {
            var members = byName[shorthand];
            groups.Add(new ShorthandGroup(shorthand, members, members.Select(m => m.ParserMethod).FirstOrDefault(m => m != null)));
        }

        return groups;
    }

    /// <summary>
    /// Whether the class has a static method of that name with the three parameters of the parser. A class that is not
    /// partial is written from outside, so the method must be reachable.
    /// </summary>
    private static bool HasParserMethod(INamedTypeSymbol type, string name, bool partial, Compilation compilation)
        => type.GetMembers(name).OfType<IMethodSymbol>().Any(m =>
            m is { IsStatic: true, Parameters.Length: 3 } && (partial || compilation.IsSymbolAccessibleWithin(m, compilation.Assembly)));

    /// <summary>
    /// Writes the statements that fill <c>table</c> with the shorthands of a class and then <paramref name="finish"/>.
    /// </summary>
    private static void WriteShorthandTable(StringBuilder sb, string indent, string typeName, List<ShorthandGroup> groups, string finish)
    {
        sb.AppendLine($"{indent}var table = new global::System.Collections.Generic.Dictionary<string, global::Content.Suil.SuilShorthandInfo>();");

        foreach (var group in groups)
        {
            var longhands = string.Join(", ", group.Members.Select(m => Literal(m.SuilName)).Distinct());

            sb.AppendLine($"{indent}table[{Literal(group.Name)}] = new global::Content.Suil.SuilShorthandInfo(");
            sb.AppendLine($"{indent}    new string[] {{ {longhands} }},");

            if (group.ParserMethod != null)
            {
                sb.AppendLine($"{indent}    {typeName}.{group.ParserMethod});");
                continue;
            }

            WriteGreedyExpander(sb, indent + "    ", group.Members);
            sb.AppendLine(");");
        }

        sb.AppendLine($"{indent}{finish}");
    }

    /// <summary>
    /// The expander that tries the parser of every longhand that has no value yet on the next value, in the order the
    /// longhands are declared, until one of them takes it. A failed attempt gives the value back.
    /// </summary>
    private static void WriteGreedyExpander(StringBuilder sb, string indent, List<ShorthandMember> members)
    {
        var names = members.Select(m => m.SuilName).Distinct().ToList();

        sb.AppendLine($"{indent}static (ref global::Content.Suil.SuilValueStream stream, global::Content.Suil.ISuilValues parsers, global::System.Collections.Generic.Dictionary<string, object> values) =>");
        sb.AppendLine($"{indent}{{");
        sb.AppendLine($"{indent}    var remaining = new global::System.Collections.Generic.HashSet<string> {{ {string.Join(", ", names.Select(Literal))} }};");
        sb.AppendLine($"{indent}    while (!stream.AtEnd)");
        sb.AppendLine($"{indent}    {{");
        sb.AppendLine($"{indent}        var outer = stream.Mark();");
        sb.AppendLine($"{indent}        var matched = false;");

        var index = 0;

        foreach (var member in members)
        {
            sb.AppendLine($"{indent}        if (!matched && remaining.Contains({Literal(member.SuilName)}))");
            sb.AppendLine($"{indent}        {{");
            sb.AppendLine($"{indent}            var mark{index} = stream.Mark();");
            sb.AppendLine($"{indent}            if (parsers.TryParse<{member.TypeName}>(ref stream, out var value{index}))");
            sb.AppendLine($"{indent}            {{");
            sb.AppendLine($"{indent}                values[{Literal(member.SuilName)}] = value{index};");
            sb.AppendLine($"{indent}                remaining.Remove({Literal(member.SuilName)});");
            sb.AppendLine($"{indent}                matched = true;");
            sb.AppendLine($"{indent}            }}");
            sb.AppendLine($"{indent}            else");
            sb.AppendLine($"{indent}            {{");
            sb.AppendLine($"{indent}                stream.Reset(mark{index});");
            sb.AppendLine($"{indent}            }}");
            sb.AppendLine($"{indent}        }}");
            index++;
        }

        sb.AppendLine($"{indent}        if (!matched)");
        sb.AppendLine($"{indent}        {{");
        sb.AppendLine($"{indent}            stream.Reset(outer);");
        sb.AppendLine($"{indent}            return false;");
        sb.AppendLine($"{indent}        }}");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine($"{indent}    return true;");
        sb.Append($"{indent}}}");
    }

    /// <summary>
    /// The public settable properties and fields declared by the type, by their names in SUIL. A member that is not
    /// public (or has a setter that is not) but has <see cref="SuilPropertyAttribute"/> goes to <paramref name="hidden"/>:
    /// only the class itself can reach it.
    /// </summary>
    private static List<Member> Members(INamedTypeSymbol type, Compilation compilation, out List<Member> hidden)
    {
        var result = new Dictionary<string, Member>(StringComparer.Ordinal);
        var hiddenResult = new Dictionary<string, Member>(StringComparer.Ordinal);

        foreach (var symbol in type.GetMembers())
        {
            ITypeSymbol valueType;
            bool canRead;
            bool isPublic;

            switch (symbol)
            {
                case IPropertySymbol property
                    when property is { IsStatic: false, IsIndexer: false, IsOverride: false, RefKind: RefKind.None }
                         && property.SetMethod is { IsInitOnly: false }:
                    valueType = property.Type;
                    canRead = property.GetMethod != null;
                    isPublic = property.DeclaredAccessibility == Accessibility.Public
                               && property.SetMethod.DeclaredAccessibility == Accessibility.Public;
                    canRead = canRead && (!isPublic || property.GetMethod!.DeclaredAccessibility == Accessibility.Public);
                    break;
                case IFieldSymbol field
                    when field is { IsStatic: false, IsReadOnly: false, IsConst: false, IsImplicitlyDeclared: false }:
                    valueType = field.Type;
                    canRead = true;
                    isPublic = field.DeclaredAccessibility == Accessibility.Public;
                    break;
                default:
                    continue;
            }

            if (!IsStylableType(valueType) || IsObsolete(symbol))
                continue;

            var name = SuilNaming.ToKebab(symbol.Name);
            string? parser = null;
            var inherited = false;

            var attribute = symbol.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == SuilViewAttributeSource.PropertyMetadataName);

            // not public and not marked: nothing to do for it
            if (!isPublic && attribute == null)
                continue;

            if (attribute != null)
            {
                if (attribute.ConstructorArguments.Length > 0 && attribute.ConstructorArguments[0].Value is string custom)
                    name = custom;

                if (attribute.ConstructorArguments.Length > 1 && attribute.ConstructorArguments[1].Value is INamedTypeSymbol parserType)
                    parser = parserType.ToDisplayString(Format);

                inherited = attribute.NamedArguments.Any(a => a is { Key: "Inherited", Value.Value: true });
            }

            var member = new Member(name, symbol.Name, valueType.ToDisplayString(Format), parser, inherited, canRead);

            if (isPublic)
                result[name] = member;
            else
                hiddenResult[name] = member;
        }

        hidden = hiddenResult.Values.OrderBy(m => m.Name, StringComparer.Ordinal).ToList();
        return result.Values.OrderBy(m => m.Name, StringComparer.Ordinal).ToList();
    }

    private static bool IsStylableType(ITypeSymbol type)
    {
        if (type.IsRefLikeType || type.TypeKind is TypeKind.Pointer or TypeKind.FunctionPointer or TypeKind.Delegate
            or TypeKind.Dynamic or TypeKind.TypeParameter or TypeKind.Error)
        {
            return false;
        }

        return type is not INamedTypeSymbol { IsGenericType: true, IsUnboundGenericType: true };
    }

    private static bool IsObsolete(ISymbol symbol)
        => symbol.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == "System.ObsoleteAttribute");

    private static string Literal(string text) => Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(text, true);
}
