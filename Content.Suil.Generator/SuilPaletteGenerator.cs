using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Content.Suil.Generator;

/// <summary>
/// Writes <c>Content.Client._RF.Suil.SuilPalette</c>: a static field for every color that <c>/variables.suil</c> gives a
/// name to (<c>let gold-fortress = #B07D2B;</c> is <c>SuilPalette.GoldFortress</c>), so C# takes the colors from the
/// same place the stylesheets do. Nothing is looked up when the game runs, and a name that is not there does not compile.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SuilPaletteGenerator : IIncrementalGenerator
{
    private const string RootProperty = "build_property.SuilRoot";
    private const string UiElementName = "Content.Client._RF.Suil.UiElement";
    private const string PalettePath = "/variables.suil";
    private const string ColorType = "global::Robust.Shared.Maths.Color";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(static t => t.Path.EndsWith(SuilPaths.Extension, StringComparison.OrdinalIgnoreCase))
            .Select(static (t, ct) => SuilSourceFile.Parse(t.Path, t.GetText(ct)?.ToString() ?? string.Empty))
            .Collect();

        var root = context.AnalyzerConfigOptionsProvider
            .Select(static (o, _) => o.GlobalOptions.TryGetValue(RootProperty, out var value) ? value : null);

        context.RegisterSourceOutput(files.Combine(root).Combine(context.CompilationProvider), static (ctx, input) =>
        {
            var ((sourceFiles, suilRoot), compilation) = input;
            Generate(ctx, sourceFiles, suilRoot, compilation);
        });
    }

    private static void Generate(
        SourceProductionContext context,
        ImmutableArray<SuilSourceFile> files,
        string? root,
        Compilation compilation)
    {
        // Only the project of the controls has a palette.
        if (string.IsNullOrWhiteSpace(root) || compilation.GetTypeByMetadataName(UiElementName) == null)
            return;

        var cleanRoot = SuilPaths.Clean(root!.Replace('\\', '/')).TrimEnd('/');
        SuilSourceFile? palette = null;

        foreach (var file in files)
        {
            var path = SuilPaths.Clean(file.Path.Replace('\\', '/'));

            if (path.StartsWith(cleanRoot + "/", StringComparison.OrdinalIgnoreCase)
                && path.Substring(cleanRoot.Length).Equals(PalettePath, StringComparison.OrdinalIgnoreCase))
            {
                palette = file;
                break;
            }
        }

        if (palette?.Tree == null)
            return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> from " + PalettePath);
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Content.Client._RF.Suil;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The colors of the SUIL theme (<c>/variables.suil</c>) for C#: <c>let gold-fortress = #B07D2B;</c> is");
        sb.AppendLine("/// <see cref=\"GoldFortress\"/>. Generated at the build, so it is always what the stylesheets use.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class SuilPalette");
        sb.AppendLine("{");

        var names = new HashSet<string>(StringComparer.Ordinal);

        foreach (var item in palette.Tree.Items)
        {
            if (item is not SuilLet let
                || let.Value is not SuilValueList { Values.Count: 1 } list
                || !TryGetColor(list.Values[0], out var color))
                continue;

            var name = ToPascalCase(let.Name);

            if (name.Length == 0 || char.IsDigit(name[0]) || !names.Add(name))
                continue;

            sb.AppendLine($"    /// <summary>The color <c>{let.Name}</c>.</summary>");
            sb.AppendLine($"    public static readonly {ColorType} {name} = {color};");
        }

        sb.AppendLine("}");
        context.AddSource("SuilPalette.g.cs", sb.ToString());
    }

    private static bool TryGetColor(ISuilValue value, out string expression)
    {
        expression = string.Empty;

        switch (value)
        {
            case SuilIdent { Value: var ident } when ident.Equals("transparent", StringComparison.OrdinalIgnoreCase):
                expression = $"{ColorType}.Transparent";
                return true;
            case SuilColor { Hex: var hex }:
                // 3 and 4 digits are the short form: each is doubled
                var full = hex.Length is 3 or 4
                    ? string.Concat(hex.Select(c => new string(c, 2)))
                    : hex;

                if (full.Length is not (6 or 8))
                    return false;

                expression = $"{ColorType}.FromHex(\"#{full}\")";
                return true;
            default:
                return false;
        }
    }

    // gold-button-color-default -> GoldButtonColorDefault
    private static string ToPascalCase(string name)
    {
        var sb = new StringBuilder();
        var upper = true;

        foreach (var c in name)
        {
            if (c is '-' or '_')
            {
                upper = true;
                continue;
            }

            if (!char.IsLetterOrDigit(c))
                return string.Empty;

            sb.Append(upper ? char.ToUpperInvariant(c) : c);
            upper = false;
        }

        return sb.ToString();
    }
}
