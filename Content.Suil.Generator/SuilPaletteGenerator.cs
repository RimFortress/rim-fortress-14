using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Content.Suil.Generator;

/// <summary>
/// Writes <c>Content.Client._RF.Suil.SuilPalette</c>: a static field for every color that <c>/variables.suil</c> gives a
/// name to (<c>let gold-fortress = #B07D2B;</c> is <c>SuilPalette.GoldFortress</c>), so C# takes the colors from the
/// same place the stylesheets do. Nothing is looked up when the game runs, and a name that is not there does not compile.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class SuilPaletteGenerator : IIncrementalGenerator
{
    private const string RootProperty = "build_property.SuilRoot";
    private const string UiElementName = "Content.Client._RF.Suil.UiElement";
    private const string PalettePath = "/variables.suil";
    private const string ColorType = "global::Robust.Shared.Maths.Color";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(static t => t.Path.EndsWith(SuilPaths.Extension, StringComparison.OrdinalIgnoreCase))
            .Select(static (t, ct) => SuilSourceFile.Parse(t.Path, t.GetText(ct)?.ToString() ?? string.Empty))
            .Collect();

        var root = context.AnalyzerConfigOptionsProvider
            .Select(static (o, _) => o.GlobalOptions.TryGetValue(RootProperty, out var value) ? value : null);

        context.RegisterSourceOutput(files.Combine(root).Combine(context.CompilationProvider), static (ctx, input) =>
        {
            var ((sourceFiles, suilRoot), compilation) = input;
            Generate(ctx, sourceFiles, suilRoot, compilation);
        });
    }

    private static void Generate(
        SourceProductionContext context,
        ImmutableArray<SuilSourceFile> files,
        string? root,
        Compilation compilation)
    {
        // Only the project of the controls has a palette.
        if (string.IsNullOrWhiteSpace(root) || compilation.GetTypeByMetadataName(UiElementName) == null)
            return;

        var cleanRoot = SuilPaths.Clean(root!.Replace('\\', '/')).TrimEnd('/');
        SuilSourceFile? palette = null;

        foreach (var file in files)
        {
            var path = SuilPaths.Clean(file.Path.Replace('\\', '/'));

            if (path.StartsWith(cleanRoot + "/", StringComparison.OrdinalIgnoreCase)
                && path.Substring(cleanRoot.Length).Equals(PalettePath, StringComparison.OrdinalIgnoreCase))
            {
                palette = file;
                break;
            }
        }

        if (palette?.Tree == null)
            return;

        // The values of the lets that are one value: the ones the colors are made of, and the colors themselves.
        var singles = new Dictionary<string, ISuilValue>(StringComparer.Ordinal);

        foreach (var item in palette.Tree.Items)
        {
            if (item is SuilLet { Value: SuilValueList { Values.Count: 1 } list } let)
                singles[let.Name] = list.Values[0];
        }

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/> from " + PalettePath);
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Content.Client._RF.Suil;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// The colors of the SUIL theme (<c>/variables.suil</c>) for C#: <c>let gold-fortress = #B07D2B;</c> is");
        sb.AppendLine("/// <see cref=\"GoldFortress\"/>. Generated at the build, so it is always what the stylesheets use.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class SuilPalette");
        sb.AppendLine("{");

        var names = new HashSet<string>(StringComparer.Ordinal);

        foreach (var pair in singles)
        {
            var resolved = Resolve(pair.Value, singles, new HashSet<string> { pair.Key });

            if (resolved == null || !IsColor(resolved))
                continue;

            var name = ToPascalCase(pair.Key);

            if (name.Length == 0 || char.IsDigit(name[0]) || !names.Add(name))
                continue;

            var expression = resolved is SuilColor { Hex: var hex } && ExpandHex(hex) is { } full
                ? $"{ColorType}.FromHex(\"#{full}\")"
                : $"global::Content.Client._RF.Suil.SuilPaletteParser.Parse(\"{pair.Key}\", {Emit(resolved)})";

            sb.AppendLine($"    /// <summary>The color <c>{pair.Key}</c>.</summary>");
            sb.AppendLine($"    public static readonly {ColorType} {name} = {expression};");
        }

        sb.AppendLine("}");
        context.AddSource("SuilPalette.g.cs", sb.ToString());
    }

    /// <summary>
    /// The value with the variables in it (<c>&lt;name&gt;</c>) replaced by what they are, or <c>null</c> if one is not
    /// known (a path, a font...) or refers to itself.
    /// </summary>
    private static ISuilValue? Resolve(ISuilValue value, Dictionary<string, ISuilValue> singles, HashSet<string> stack)
    {
        switch (value)
        {
            case SuilVariable variable:
                if (!singles.TryGetValue(variable.Name, out var known) || !stack.Add(variable.Name))
                    return null;

                var inner = Resolve(known, singles, stack);
                stack.Remove(variable.Name);
                return inner;
            case SuilFunction function:
                var arguments = new List<List<ISuilValue>>();

                foreach (var argument in function.Arguments)
                {
                    var values = new List<ISuilValue>();

                    foreach (var item in argument)
                    {
                        var resolved = Resolve(item, singles, stack);

                        if (resolved == null)
                            return null;

                        values.Add(resolved);
                    }

                    arguments.Add(values);
                }

                return new SuilFunction(function.Name, arguments);
            default:
                return value;
        }
    }

    private static bool IsColor(ISuilValue value) => value switch
    {
        SuilColor { Hex: var hex } => ExpandHex(hex) != null,
        SuilIdent { Value: var ident } => ColorNames.Contains(ident.ToLowerInvariant()),
        SuilFunction { Name: var function } => function.ToLowerInvariant() is "rgb" or "rgba" or "color-mix",
        _ => false,
    };

    // 3 and 4 digits are the short form: each is doubled
    private static string? ExpandHex(string hex)
    {
        var full = hex.Length is 3 or 4 ? string.Concat(hex.Select(c => new string(c, 2))) : hex;
        return full.Length is 6 or 8 ? full : null;
    }

    /// <summary>
    /// The C# that builds the value, for <c>SuilPaletteParser</c>.
    /// </summary>
    private static string Emit(ISuilValue value)
    {
        switch (value)
        {
            case SuilColor color:
                return $"new global::Content.Suil.SuilColor(\"{color.Hex}\")";
            case SuilIdent ident:
                return $"new global::Content.Suil.SuilIdent(\"{ident.Value}\")";
            case SuilNumber number:
                return $"new global::Content.Suil.SuilNumber({Literal(number.Value)}, {(number.IsInteger ? "true" : "false")})";
            case SuilPercentage percentage:
                return $"new global::Content.Suil.SuilPercentage({Literal(percentage.Value)})";
            case SuilFunction function:
                var arguments = string.Join(", ", function.Arguments.Select(argument =>
                    "new global::System.Collections.Generic.List<global::Content.Suil.ISuilValue> { "
                    + string.Join(", ", argument.Select(Emit)) + " }"));
                return $"new global::Content.Suil.SuilFunction(\"{function.Name}\", "
                       + "new global::System.Collections.Generic.List<global::System.Collections.Generic.List<global::Content.Suil.ISuilValue>> { "
                       + arguments + " })";
            default:
                // Not something a color is made of: the parser says no to it.
                return "new global::Content.Suil.SuilIdent(\"?\")";
        }
    }

    private static string Literal(double value)
        => value.ToString("R", System.Globalization.CultureInfo.InvariantCulture) + "d";

