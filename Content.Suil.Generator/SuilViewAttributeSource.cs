namespace Content.Suil.Generator;

/// <summary>
/// The text of the attribute that the generator adds to the compilation by itself, so the project that uses
/// [SuilView] doesn't need a reference to anything (and nothing of SUIL has to be shipped with the game).
/// </summary>
internal static class SuilViewAttributeSource
{
    public const string MetadataName = "Content.Suil.SuilViewAttribute";

    public const string TagMetadataName = "Content.Suil.SuilTagAttribute";

    public const string HintName = "SuilViewAttribute.g.cs";

    public const string Text = """
        // <auto-generated>
        // The attribute of the SUIL source generator, see Content.Suil.Generator.
        // </auto-generated>
        #nullable enable
        namespace Content.Suil
        {
            /// <summary>
            /// Marks the code-behind class of a .suil file. The source generator reads the file and adds to the class
            /// the fields of the elements with an id and the <c>InitializeComponent()</c> method that builds the tree:
            /// <code>
            /// [SuilView("/Lobby/CharacterPickerButton.suil")]
            /// public sealed partial class CharacterPickerButton : CssButton
            /// {
            ///     public CharacterPickerButton() { InitializeComponent(); }
            /// }
            /// </code>
            /// The class must be partial and derive from the type of the root element of the file.
            /// With <see cref="Name"/> the class is also registered as a tag, so other .suil files can use it as an element.
            /// </summary>
            [global::System.AttributeUsage(global::System.AttributeTargets.Class, AllowMultiple = false, Inherited = false)]
            internal sealed class SuilViewAttribute : global::System.Attribute
            {
                public SuilViewAttribute(string path)
                {
                    Path = path;
                }

                /// <summary>
                /// The path of the .suil file in the form of the resource path, like <c>/Lobby/Screen.suil</c>, relative to Resources/UI.
                /// The extension may be omitted. The folder of the files is the <c>SuilRoot</c> build property.
                /// </summary>
                public string Path { get; }

                /// <summary>
                /// The custom tag of the class in SUIL, like <c>character-picker</c>. Without it the tag is the name of the
                /// class in kebab-case (<c>CharacterPicker</c> is <c>character-picker</c>).
                /// </summary>
                public string? Name { get; set; }
            }

            /// <summary>
            /// Gives a control type a custom tag in SUIL; without it the tag is the class name in kebab-case, so this
            /// is only for the names that are not the class names. A class that has a custom tag is known only by it. On the class: <c>[SuilTag("fancy-button")]</c>. For a type that can't
            /// be marked (the engine's or the one of another project), on the assembly:
            /// <c>[assembly: SuilTag("sprite-view", typeof(SpriteView))]</c>. The tag <c>_</c> is the type of the
            /// element written as <c>_</c>.
            /// </summary>
            [global::System.AttributeUsage(
                global::System.AttributeTargets.Class | global::System.AttributeTargets.Assembly,
                AllowMultiple = true,
                Inherited = false)]
            internal sealed class SuilTagAttribute : global::System.Attribute
            {
                public SuilTagAttribute(string name)
                {
                    Name = name;
                }

                public SuilTagAttribute(string name, global::System.Type type)
                {
                    Name = name;
                    Type = type;
                }

                public string Name { get; }

                public global::System.Type? Type { get; }
            }
        }
        """;
}
